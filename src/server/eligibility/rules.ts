/**
 * Retrieves the eligibility rule for a service, or provides a structured default rule.
 */
export function getServiceEligibilityRule(slugOrKey: string): ServiceEligibilityRule {
  const norm = slugOrKey.toLowerCase().replace(/[^a-z0-9]+/g, "-").trim();
  if (SERVICE_ELIGIBILITY_RULES[norm]) {
    return SERVICE_ELIGIBILITY_RULES[norm];
  }

  // Fallback generic rule
  return {
    serviceId: norm,
    serviceName: slugOrKey,
    acceptedNationalities: ["Indian"],
    customConditionSummary: "Citizen must satisfy standard conducting authority eligibility regulations.",
    sourceReference: "Official Conducting Authority Portal",
    sourceUrl: null,
  };
}
